const BY_SLUG = new Map(SERVICES.map((s) => [s.slug, s]));
export const findService = (slug: string | null | undefined) =>
  slug ? BY_SLUG.get(slug) : undefined;

// WCAG contrast of a brand colour against the white icon tile. Pale brand colours (e.g. a light
// mint) would be nearly invisible there, so those icons are drawn in the text colour instead.
function contrastOnWhite(hex: string): number {
  const channel = (i: number) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  const luminance = 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4);
  return 1.05 / (luminance + 0.05);
}

export const iconColor = (icon: SimpleIcon) =>
  contrastOnWhite(icon.hex) >= 2.5 ? `#${icon.hex}` : 'var(--text)';
